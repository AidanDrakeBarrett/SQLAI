import json
from openai import OpenAI
import os
import sqlite3
from time import time

fdir = os.getcwd()
def getPath(fname):
    return os.path.join(fdir, fname)

sqliteDbPath = getPath("aidb.sqlite")
setupSqlPath = getPath("setup.sql")
setupSqlDataPath = getPath("setupData.sql")

if os.path.exists(sqliteDbPath):
    os.remove(sqliteDbPath)

sqliteCon = sqlite3.connect(sqliteDbPath)
sqliteCursor = sqliteCon.cursor()

with (
    open(setupSqlPath) as setupSqlFile,
    open(setupSqlDataPath) as setupSqlDataFile
):
    setupSqlScript = setupSqlFile.read()
    setupSqlDataScript = setupSqlDataFile.read()

# Execute setup scripts to actually create and populate the tables
sqliteCursor.executescript(setupSqlScript)
sqliteCursor.executescript(setupSqlDataScript)
sqliteCon.commit()

def runSql(query):
    result = sqliteCursor.execute(query).fetchall()
    return result

configPath = getPath("config.json")
with open(configPath) as configFile:
    config = json.load(configFile)

openAiClient = OpenAI(api_key = config["openaiKey"])
#openAiClient.models.list()
chosen_model = "gpt-6-luna"

def getChatResponse(content):
    stream = openAiClient.chat.completions.create(
        model=chosen_model,
        messages=[{"role": "user", "content": content}],
        stream=True,
    )

    responseList = []
    for chunk in stream:
        if chunk.choices[0].delta.content is not None:
            responseList.append(chunk.choices[0].delta.content)

    result = "".join(responseList)
    return result

commonSqlOnlyRequest = " Give me a sqlite select statement that answers the question. Only respond with sqlite syntax. If there is an error do not explain it!"
strategies = {
    "zero_shot": setupSqlScript + commonSqlOnlyRequest,
    "single_domain": (setupSqlScript + " Who owns Neuroshock? " +
        " Select username\nfrom users\nleft join user_library on users.user_id = user_library.user_id\nleft join games on game_lib.game_id = games.game_id\nwhere game_name = 'Neuroshock';\n" +
        commonSqlOnlyRequest)
}#FIXME: EXPAND ME

questions = [
    "Who is friends with courrierr666?",
    "Who owns Neuroshock?",
    "How many total hours have people played Halved Vitality?",
    "What is the most popular game by total hours played?",
    "Which game, or games if there is a tie, have people bought the most?",
    "What are the reviews and names of games tagged with 'Horror'?",
    "What games are owned by courrierr666 and both of his friends?"
]

def sanitizeForJustSql(value):
    gptStartSqlMarker = "```"
    gptEndSqlMarker = "```"
    if gptStartSqlMarker in value:
        value = value.split(gptStartSqlMarker, 1)[1]
        newline_index = value.find("\n")
        if newline_index != -1:
            value = value[newline_index + 1:]
    if gptEndSqlMarker in value:
        value = value.split(gptEndSqlMarker, 1)[0]
    return value.strip()

for strategy in strategies:
    responses = {"strategy": strategy, "prompt_prefix": strategies[strategy]}
    questionResults = []
    print("#~#~#~#")
    print(f"Running strategy: {strategy}")
    for question in questions:
        print("?~?~?~?")
        print("Question:")
        print(question)
        error = "None"
        queryRawResponse = ""
        sqlSyntaxResponse = ""

        try:
            getSqlFromQuestionEngineeredPrompt = strategies[strategy] + " " + question
            sqlSyntaxResponse = getChatResponse(getSqlFromQuestionEngineeredPrompt)
            sqlSyntaxResponse = sanitizeForJustSql(sqlSyntaxResponse)
            print("SQL Syntax Response:")
            print(sqlSyntaxResponse)
            queryRawResponse = str(runSql(sqlSyntaxResponse))
            print("Query Raw Response:")
            print(queryRawResponse)

            friendlyResultsPrompt = "I asked the question \"" + question + "\" and the result of the query was \"" + queryRawResponse + ".\" Can you phrase these results in a sentence? Don't give any suggestions afterwards."
            friendlyResults = getChatResponse(friendlyResultsPrompt)
            print("Friendly Response:")
            print(friendlyResults)

        except Exception as err:
            error = str(err)
            print(err)

        questionResults.append({
            "question": question,
            "sql": sqlSyntaxResponse,
            "queryRawResponse": queryRawResponse,
            "friendlyResponse": friendlyResults,
            "error": error
        })
    responses["questionResults"] = questionResults

    with open(getPath(f"response_{strategy}_{time()}.json"), "w") as outfile:
        json.dump(responses, outfile, indent = 2)

sqliteCursor.close()
sqliteCon.close()
print("Done")